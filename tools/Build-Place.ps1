$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$buildRoot = Join-Path $projectRoot 'builds'
New-Item -ItemType Directory -Path $buildRoot -Force | Out-Null
$sourceFiles = @{}
Get-ChildItem -LiteralPath (Join-Path $projectRoot 'game') -File | ForEach-Object {
    $sourceFiles[$_.Name] = [IO.File]::ReadAllText($_.FullName)
}
$settings = [Xml.XmlWriterSettings]::new()
$settings.Indent = $true
$settings.Encoding = [Text.UTF8Encoding]::new($false)
$placePath = Join-Path $buildRoot 'BrainrotSignal.rbxlx'
$placeWriter = [Xml.XmlWriter]::Create($placePath, $settings)
$script:signalBuildReferent = 0
function Write-Instance {
    param([string]$Class, [string]$Name, [string]$Source, [scriptblock]$Children)
    $placeWriter.WriteStartElement('Item')
    $placeWriter.WriteAttributeString('class', $Class)
    $script:signalBuildReferent += 1
    $placeWriter.WriteAttributeString('referent', ('RBX{0:D8}' -f $script:signalBuildReferent))
    $placeWriter.WriteStartElement('Properties')
    $placeWriter.WriteStartElement('string')
    $placeWriter.WriteAttributeString('name', 'Name')
    $placeWriter.WriteString($Name)
    $placeWriter.WriteEndElement()
    if ($Source) {
        $placeWriter.WriteStartElement('ProtectedString')
        $placeWriter.WriteAttributeString('name', 'Source')
        $placeWriter.WriteCData($Source)
        $placeWriter.WriteEndElement()
    }
    $placeWriter.WriteEndElement()
    if ($Children) { & $Children }
    $placeWriter.WriteEndElement()
}
try {
    $placeWriter.WriteStartDocument()
    $placeWriter.WriteStartElement('roblox')
    $placeWriter.WriteAttributeString('version', '4')
    Write-Instance 'Workspace' 'Workspace' '' {}
    Write-Instance 'ReplicatedStorage' 'ReplicatedStorage' '' {
        Write-Instance 'ModuleScript' 'SignalConfig' $sourceFiles['Config.luau']
        Write-Instance 'ModuleScript' 'SignalCreature' $sourceFiles['Creature.luau']
    }
    Write-Instance 'ServerScriptService' 'ServerScriptService' '' {
        Write-Instance 'ModuleScript' 'SignalWorld' $sourceFiles['World.luau']
        Write-Instance 'Script' 'SignalServer' $sourceFiles['Server.server.luau']
    }
    Write-Instance 'StarterPlayer' 'StarterPlayer' '' {
        Write-Instance 'StarterPlayerScripts' 'StarterPlayerScripts' '' {
            Write-Instance 'LocalScript' 'SignalClient' $sourceFiles['Client.client.luau']
        }
    }
    $placeWriter.WriteEndElement()
    $placeWriter.WriteEndDocument()
} finally { $placeWriter.Dispose() }

$install = [Text.StringBuilder]::new()
[void]$install.AppendLine('-- Generated by tools/Build-Place.ps1. Paste into the Studio Command Bar in Edit mode.')
[void]$install.AppendLine('local RS=game:GetService("ReplicatedStorage") local SSS=game:GetService("ServerScriptService") local SPS=game:GetService("StarterPlayer").StarterPlayerScripts')
$entries = @(
    @('Config.luau','SignalConfig','ModuleScript','RS'),
    @('Creature.luau','SignalCreature','ModuleScript','RS'),
    @('World.luau','SignalWorld','ModuleScript','SSS'),
    @('Server.server.luau','SignalServer','Script','SSS'),
    @('Client.client.luau','SignalClient','LocalScript','SPS')
)
foreach ($entry in $entries) {
    $src = $sourceFiles[$entry[0]]
    if ($src.Contains(']====]')) { throw 'Source contains installer delimiter.' }
    [void]$install.AppendLine(('do local old={0}:FindFirstChild("{1}") if old then old:Destroy() end local s=Instance.new("{2}") s.Name="{1}" s.Source=[====[{3}]====] s.Parent={0} end' -f $entry[3],$entry[1],$entry[2],$src))
}
[void]$install.AppendLine('require(SSS.SignalWorld).Build() print("Brainrot Signal Simulator installed")')
[IO.File]::WriteAllText((Join-Path $buildRoot 'Install.commandbar.luau'), $install.ToString(), [Text.UTF8Encoding]::new($false))
Write-Output "Built $placePath and the Edit-mode installer."
